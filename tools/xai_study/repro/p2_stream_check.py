#!/usr/bin/env python3
"""Paper-2 stream validation: jutari vs xitari on the EXACT shared-testbed streams.

P2 scores every game at f* = 90 and reads outputs at f* + 15 = 105, beyond Paper 1's
30-RAM / 60-screen validated window. This checks, per scored game, that jutari and the
seed-patched xitari reference agree on every frame 0..105 of that stream.

Inputs (one directory):
  <game>.actions.txt, <game>.jutari.bin, <game>.meta.json  from p2_stream_dump.jl
  <game>.xitari.jsonl  from trace_min (xitari) via p2_stream_xitari.sh. Since 2026-10-26 the
                       P2 runners boot every game with its real RomSettings
                       (common/game_sets.jl::xai_settings_for = Paper-1's conformance map),
                       so xitari runs with its default ALE starting actions. Before that,
                       37 games booted with GenericRomSettings; validate those old streams
                       with XI_NO_STARTING_ACTIONS=1.

  python3 tools/xai_study/repro/p2_stream_check.py DIR [--md OUT.md]

Per game: first RAM-divergent frame (+ bytes), first screen-divergent frame (+ pixels),
and whether the run is exact through frame 105 and through f* = 90.
"""
import json
import os
import sys

RAM, H, W = 128, 210, 160


def load_jutari(path, hw):
    d = open(path, "rb").read()
    step = RAM + hw[0] * hw[1]
    n = (len(d) - RAM) // step
    rams = [d[:RAM]] + [d[RAM + k * step: RAM + k * step + RAM] for k in range(n)]
    scrs = [None] + [d[RAM + k * step + RAM: RAM + (k + 1) * step] for k in range(n)]
    return rams, scrs


def load_xitari(path):
    rams, scrs, dims = [], [], []
    for line in open(path):
        r = json.loads(line)
        rams.append(bytes.fromhex(r["ram"]))
        scrs.append(bytes.fromhex(r["screen"]) if "screen" in r else None)
        dims.append((r.get("h"), r.get("w")))
    return rams, scrs, dims


def check(d, game):
    hw = tuple(json.load(open(os.path.join(d, f"{game}.meta.json"))).get("screen_hw", (H, W)))
    jr, js = load_jutari(os.path.join(d, f"{game}.jutari.bin"), hw)
    xr, xs, xd = load_xitari(os.path.join(d, f"{game}.xitari.jsonl"))
    n = min(len(jr), len(xr))
    ram_first = next((k for k in range(n) if jr[k] != xr[k]), None)
    scr_first, dims_ok = None, True
    for k in range(1, n):
        if xd[k] != hw:
            dims_ok = False
            break
        if js[k] != xs[k]:
            scr_first = k
            break
    out = {"game": game, "frames_compared": n - 1, "ram_first_divergence": ram_first,
           "screen_first_divergence": scr_first, "screen_dims_match": dims_ok,
           "xitari_screen_dims": xd[1] if len(xd) > 1 else None}
    if ram_first is not None:
        out["ram_bytes_differing"] = [i for i in range(RAM) if jr[ram_first][i] != xr[ram_first][i]]
    if scr_first is not None:
        out["screen_px_differing"] = sum(a != b for a, b in zip(js[scr_first], xs[scr_first]))
    ok = lambda f, lim: f is None or f > lim
    out["ram_exact_to_105"] = ram_first is None and n - 1 >= 105
    out["screen_exact_to_105"] = dims_ok and scr_first is None and n - 1 >= 105
    out["ram_exact_to_fstar"] = ok(ram_first, 90)
    return out


def main(argv):
    d = argv[0]
    md = argv[argv.index("--md") + 1] if "--md" in argv else None
    games = sorted(f[:-len(".jutari.bin")] for f in os.listdir(d) if f.endswith(".jutari.bin"))
    res = [check(d, g) for g in games if os.path.exists(os.path.join(d, f"{g}.xitari.jsonl"))]
    nr = sum(r["ram_exact_to_105"] for r in res)
    ns = sum(r["screen_exact_to_105"] for r in res)
    print(f"RAM exact through frame 105: {nr}/{len(res)}   screen: {ns}/{len(res)}")
    for r in res:
        if not (r["ram_exact_to_105"] and r["screen_exact_to_105"]):
            print("  ", json.dumps(r))
    json.dump(res, open(os.path.join(d, "p2_stream_check.json"), "w"), indent=1)
    if md:
        with open(md, "w") as f:
            f.write("# Paper-2 stream validation — jutari vs xitari, frames 0–105\n\n")
            f.write("Exact P2 shared-testbed streams (seed 0, 90-frame prefix + 15-frame horizon), "
                    "standard ALE boot (60 NOOP + 4 RESET + the game's starting actions), seed-patched "
                    "xitari. Generated by `tools/xai_study/repro/p2_stream_check.py`.\n\n")
            f.write(f"**RAM exact on every frame 0–105: {nr}/{len(res)}; screen: {ns}/{len(res)}.**\n\n")
            f.write("| game | RAM | first RAM diff (bytes) | screen | first screen diff (px) |\n|---|---|---|---|---|\n")
            for r in res:
                rd = "—" if r["ram_first_divergence"] is None else f"{r['ram_first_divergence']} ({r['ram_bytes_differing']})"
                sd = ("dims " + str(r["xitari_screen_dims"])) if not r["screen_dims_match"] else (
                    "—" if r["screen_first_divergence"] is None else f"{r['screen_first_divergence']} ({r['screen_px_differing']})")
                f.write(f"| {r['game']} | {'✓' if r['ram_exact_to_105'] else '✗'} | {rd} | "
                        f"{'✓' if r['screen_exact_to_105'] else '✗'} | {sd} |\n")
    return 0 if nr == len(res) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
