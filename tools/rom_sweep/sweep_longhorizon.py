#!/usr/bin/env python3
"""Long-horizon conformance sweep: all 64 conformance ROMs, jutari vs xitari, RAM and
screen on EVERY frame of the full standard action stream (default 3,600 steps) —
the in-window protocol (30-frame RAM / 60-frame screen) run 60x longer.

Uses exactly the conformance harnesses (sweep_jutari_ram.py, sweep_jutari_screen.py):
same boot, same RomSettings, same action stream, no game-over auto-reset on either
side. (The comparison-video pipeline, tools/longhorizon_diff.py, auto-resets on game
over in each dumper; its divergences can come from that wrapper — e.g. qbert/gravitar
diverge there at ~1,865/1,930 but are RAM- and pixel-exact here.)

The reference must be the seed-patched xitari (tools/xitari_conformance_seed.patch).

  python3 tools/rom_sweep/sweep_longhorizon.py [--jobs N] [--frames N]
"""
from __future__ import annotations
import argparse, subprocess, sys, tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
OUT = REPO / "tools/rom_sweep/results_longhorizon.md"


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--jobs", type=int, default=6)
    p.add_argument("--frames", type=int, default=3600)
    p.add_argument("--games", nargs="*", default=None)
    a = p.parse_args(argv)
    sel = ["--games", *a.games] if a.games else []
    with tempfile.TemporaryDirectory() as td:
        ram, scr = Path(td) / "ram.md", Path(td) / "screen.md"
        for script, out in (("sweep_jutari_ram.py", ram), ("sweep_jutari_screen.py", scr)):
            subprocess.run([sys.executable, str(REPO / "tools/rom_sweep" / script),
                            "--jobs", str(a.jobs), "--frames", str(a.frames),
                            "--out", str(out), *sel], check=True)
        body = ["# Long-horizon conformance sweep (all 64 ROMs, RAM + screen)", "",
                f"jutari vs seed-patched xitari on every one of {a.frames} frames of "
                "`breakout_random_actions.txt` after the standard boot, using the in-window "
                "conformance harnesses unchanged (no game-over auto-reset). Generated by "
                "`tools/rom_sweep/sweep_longhorizon.py`.", "",
                "## RAM", "", *ram.read_text().splitlines()[1:], "",
                "## Screen", "", *scr.read_text().splitlines()[1:]]
    OUT.write_text("\n".join(body) + "\n")
    print(f"wrote {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
